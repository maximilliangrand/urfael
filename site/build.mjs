// Builds the site's figures: `npm run build:site` from the repo root.
//   docs/assets/figures.js            site/main.ts with the engine, the plate and every registered figure: one minified ES module
//   docs/assets/plate.css             one --fig-ratio rule per registered figure, then site/plate.css, minified
//   docs/assets/LICENSE-hairline.txt  the engine's MIT licence, shipped with the code it covers (figures.js names it)
// The outputs are committed, so docs/ stays a static site that deploys without a build step.
import { build, transform } from 'esbuild'
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { gzipSync } from 'node:zlib'

const SITE = dirname(fileURLToPath(import.meta.url))
const ROOT = dirname(SITE)
const OUT = join(ROOT, 'docs', 'assets')
// what the engine already asks of a browser (aspect-ratio, :where, ResizeObserver, IntersectionObserver)
const BROWSERS = ['chrome100', 'edge100', 'firefox100', 'safari15']

/** Each registered figure's name and aspect ratio, from the registry itself, run in Node: figures touch no DOM at import. */
async function ratios() {
  const r = await build({
    stdin: { contents: "export { FIGURES } from './figures/index.ts'; export { ratio } from './hairline/mount.ts';", resolveDir: SITE, loader: 'ts' },
    bundle: true, write: false, format: 'esm', platform: 'neutral', logLevel: 'silent',
  })
  const url = 'data:text/javascript;base64,' + Buffer.from(r.outputFiles[0].text).toString('base64')
  const { FIGURES, ratio } = await import(url)
  return Object.entries(FIGURES).map(([name, spec]) => {
    if (spec.id !== name) throw new Error(`figures/index.ts: "${name}" has id "${spec.id}"; a figure's key and id must match`)
    return [name, ratio(spec)]
  })
}

const kb = (text) => `${(Buffer.byteLength(text) / 1024).toFixed(1)} kB, ${(gzipSync(text).length / 1024).toFixed(1)} kB gzipped`

mkdirSync(OUT, { recursive: true })

const js = await build({
  entryPoints: [join(SITE, 'main.ts')],
  bundle: true, write: false, format: 'esm', minify: true, target: BROWSERS,
  legalComments: 'eof', charset: 'utf8', logLevel: 'warning',
})
const figuresJs = js.outputFiles[0].text
writeFileSync(join(OUT, 'figures.js'), figuresJs)
// the MIT licence asks that its notice travel with every copy: figures.js carries the engine, so the licence goes beside it
copyFileSync(join(SITE, 'hairline', 'LICENSE'), join(OUT, 'LICENSE-hairline.txt'))

const shapes = await ratios()
const generated = shapes.map(([name, r]) => `.plate[data-figure="${name}"]{--fig-ratio:${r}}`).join('\n')
const css = await transform(`/* generated by site/build.mjs from site/figures/index.ts */\n${generated}\n${readFileSync(join(SITE, 'plate.css'), 'utf8')}`, {
  loader: 'css', minify: true, target: BROWSERS, logLevel: 'warning',
})
writeFileSync(join(OUT, 'plate.css'), css.code)

console.log(`${relative(ROOT, join(OUT, 'figures.js'))}  ${kb(figuresJs)}`)
console.log(`${relative(ROOT, join(OUT, 'plate.css'))}   ${kb(css.code)}`)
console.log(`${relative(ROOT, join(OUT, 'LICENSE-hairline.txt'))}  the engine's licence`)
console.log(`figures   ${shapes.map(([name, r]) => `${name} ${r}`).join(', ') || 'none registered'}`)
