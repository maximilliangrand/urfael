// Writes the icon set to docs/assets/icons/: `npm run build:icons` from the repo root.
//
//   <name>.svg          the full variant, every detail, for 96px and up
//   <name>-compact.svg  the compact variant, for under 96px
//   sprite.svg          every icon as a <symbol>, ids <name> and <name>-compact:
//                       <svg width="56" height="56" aria-hidden="true"><use href="/assets/icons/sprite.svg#voice-compact"/></svg>
//   icons.json          { name: { page, card, shows, full: { viewBox, svg }, compact: { viewBox, svg } } }
//   icons.css           optional: re-themes icons pasted inline, by class (wash band, night band, forced colours)
//
// The set is strictly monochrome: the build fails if any colour in a palette or in a file it writes is not a
// neutral grey (red, green and blue equal), so no hue can come back by accident.
//
// Each file is inline-ready: paste it into the page, or use it as <img src alt="">. The text beside an icon
// carries its meaning, so the icon is decorative (aria-hidden). The outputs are committed, so docs/ stays a
// static site that deploys without a build step. The drawings are in site/icons/set/; to look at them, run
// `node site/icons/sheet.mjs`.
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { gzipSync } from 'node:zlib'
import { ICON_DIR, loadIcons } from './load.mjs'

const ROOT = dirname(dirname(ICON_DIR))
const OUT = join(ROOT, 'docs', 'assets', 'icons')

const { ICONS, ABOUT, PALETTE, svg, symbol } = await loadIcons()
const names = Object.keys(ICONS)

/** WCAG 2.x contrast of two hex colours. */
function contrast(a, b) {
  const lum = (hex) => {
    const [r, g, bl] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4))
    return 0.2126 * r + 0.7152 * g + 0.0722 * bl
  }
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p)
  return (x + 0.05) / (y + 0.05)
}

/** The night band's palette: white linework on black, greys for the hairlines, white as the bright mark. */
const NIGHT = { ground: '#000000', edge: '#b3b3b3', mid: '#808080', lo: '#4d4d4d', accent: '#ffffff', ink: '#1c1c1c', warm: '#ffffff', blush: '#6e6e6e' }
/** The wash band, the page's quiet grey, for an icon that sits on it rather than on white. */
const WASH = '#fafafa'

const failures = []
const check = (ok, message) => { if (!ok) failures.push(message) }
/** A neutral grey: a #rrggbb whose red, green and blue are equal. */
const grey = (hex) => /^#([0-9a-f]{2})\1\1$/i.test(hex)
for (const [where, paint] of [...Object.entries(PALETTE), ['night', NIGHT], ['wash band', { ground: WASH }]]) {
  for (const [tone, hex] of Object.entries(paint)) check(grey(hex), `${where} ${tone} ${hex} is not a neutral grey`)
}
for (const [variant, paint] of Object.entries(PALETTE)) {
  for (const ground of [paint.ground, WASH]) {
    check(contrast(paint.edge, ground) >= 4.5, `${variant} edge on ${ground}: ${contrast(paint.edge, ground).toFixed(2)}:1`)
    check(contrast(paint.accent, ground) >= 4.5, `${variant} accent on ${ground}: ${contrast(paint.accent, ground).toFixed(2)}:1`)
  }
  check(contrast(paint.warm, paint.ink) >= 4.5, `${variant} eyes on the face window: ${contrast(paint.warm, paint.ink).toFixed(2)}:1`)
}
check(contrast(NIGHT.edge, NIGHT.ground) >= 4.5 && contrast(NIGHT.accent, NIGHT.ground) >= 4.5, 'night edge or accent under 4.5:1')
check(contrast(NIGHT.warm, NIGHT.ink) >= 4.5, 'night eyes on the face window under 4.5:1')

const css = `/* Urfael icons: optional rules for icons pasted inline. Generated by site/icons/build.mjs; do not edit.
   Each icon carries its light palette as presentation attributes, for a white page (#ffffff), and works
   without this file. These rules only re-theme it: put the class on the svg or on any ancestor. A plain
   solid takes its paint from the svg element, a classed mark from its class. */
.u-icon { display: inline-block; flex: none; vertical-align: middle; overflow: visible; }

/* on the wash band rather than white: the solids take the band's colour */
:is(.u-icon-wash .u-icon, .u-icon.u-icon-wash), .u-icon-wash .ui-f-g { fill: ${WASH}; }

/* on the night band */
:is(.u-icon-night .u-icon, .u-icon.u-icon-night) { fill: ${NIGHT.ground}; stroke: ${NIGHT.edge}; }
.u-icon-night .ui-f-g { fill: ${NIGHT.ground}; }
.u-icon-night .ui-s-e { stroke: ${NIGHT.edge}; }
.u-icon-night .ui-s-m { stroke: ${NIGHT.mid}; }
.u-icon-night .ui-s-l { stroke: ${NIGHT.lo}; }
.u-icon-night .ui-s-a { stroke: ${NIGHT.accent}; }
.u-icon-night .ui-f-e { fill: ${NIGHT.edge}; }
.u-icon-night .ui-f-m { fill: ${NIGHT.mid}; }
.u-icon-night .ui-f-l { fill: ${NIGHT.lo}; }
.u-icon-night .ui-f-a { fill: ${NIGHT.accent}; }
.u-icon-night .ui-f-k { fill: ${NIGHT.ink}; }
.u-icon-night .ui-f-w { fill: ${NIGHT.warm}; }
.u-icon-night .ui-f-b { fill: ${NIGHT.blush}; }

/* forced colours: lines and the accent in the text colour, solids in the canvas; Uru's eyes and cheeks in the canvas on its window */
@media (forced-colors: active) {
  .u-icon { fill: Canvas; stroke: CanvasText; }
  .u-icon :is(.ui-s-e, .ui-s-m, .ui-s-l, .ui-s-a) { stroke: CanvasText; }
  .u-icon .ui-f-g { fill: Canvas; }
  .u-icon :is(.ui-f-e, .ui-f-m, .ui-f-l, .ui-f-k, .ui-f-a) { fill: CanvasText; }
  .u-icon :is(.ui-f-w, .ui-f-b) { fill: Canvas; }
  .u-icon .ui-lt { stroke: CanvasText; }
  .u-icon .ui-lt-g { fill: Canvas; }
}
`

const files = {}
const json = {}
for (const name of names) {
  const about = ABOUT[name]
  json[name] = { ...about }
  for (const variant of ['full', 'compact']) {
    const markup = svg(name, variant)
    files[variant === 'full' ? `${name}.svg` : `${name}-compact.svg`] = markup
    json[name][variant] = { viewBox: markup.match(/viewBox="([^"]+)"/)[1], svg: markup }
    check(!/<text|<image|filter|<style|var\(|url\(|NaN|Infinity/.test(markup), `${name} ${variant}: holds text, a filter, a style, a variable, a reference or a bad number`)
    check(markup.includes('ui-s-a') || markup.includes('ui-f-a') || markup.includes('ui-f-w'), `${name} ${variant}: no accent part`)
  }
}
files['sprite.svg'] = `<svg xmlns="http://www.w3.org/2000/svg">${names.flatMap((n) => [symbol(n, 'full'), symbol(n, 'compact')]).join('')}</svg>\n`
files['icons.json'] = JSON.stringify(json, null, 2) + '\n'
files['icons.css'] = css
// every colour the build writes, in any file: a neutral grey, or the build stops
for (const [file, text] of Object.entries(files)) {
  const tinted = [...new Set(text.match(/#[0-9a-f]{3,8}\b/gi) ?? [])].filter((hex) => !grey(hex.length === 4 ? `#${[...hex.slice(1)].map((c) => c + c).join('')}` : hex))
  check(!tinted.length, `${file}: ${tinted.join(', ')} not a neutral grey`)
}

if (failures.length) {
  console.error(failures.map((f) => `FAIL ${f}`).join('\n'))
  process.exit(1)
}

mkdirSync(OUT, { recursive: true })
for (const old of readdirSync(OUT)) if (!(old in files)) rmSync(join(OUT, old))
for (const [file, text] of Object.entries(files)) writeFileSync(join(OUT, file), file.endsWith('.svg') && !file.startsWith('sprite') ? text + '\n' : text)

const kb = (text) => `${(Buffer.byteLength(text) / 1024).toFixed(1)} kB (${(gzipSync(text).length / 1024).toFixed(1)} kB gz)`
const sizes = names.map((n) => Buffer.byteLength(files[`${n}.svg`]))
console.log(`${relative(ROOT, OUT)}/  ${names.length} icons, ${names.length * 2} svg files`)
console.log(`  full svg   ${(Math.min(...sizes) / 1024).toFixed(1)} to ${(Math.max(...sizes) / 1024).toFixed(1)} kB each`)
console.log(`  sprite.svg ${kb(files['sprite.svg'])}`)
console.log(`  icons.json ${kb(files['icons.json'])}`)
console.log(`  contrast   edge ${contrast(PALETTE.full.edge, PALETTE.full.ground).toFixed(1)}:1, accent ${contrast(PALETTE.full.accent, PALETTE.full.ground).toFixed(1)}:1 on white; eyes ${contrast(PALETTE.full.warm, PALETTE.full.ink).toFixed(1)}:1 on the face window`)
console.log(`  ${names.join(', ')}`)
